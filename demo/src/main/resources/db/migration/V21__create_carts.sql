CREATE TABLE carts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    CONSTRAINT uk_carts_user_id UNIQUE (user_id),
    CONSTRAINT fk_carts_user_id FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE cart_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id BIGINT NOT NULL,
    product_id UUID NOT NULL,
    product_variant_id UUID NOT NULL,
    quantity INTEGER NOT NULL,
    selected BOOLEAN NOT NULL,
    added_at TIMESTAMPTZ NOT NULL,
    public_product_name TEXT NOT NULL,
    public_sku TEXT NOT NULL,
    public_options JSONB NOT NULL,
    CONSTRAINT uk_cart_items_cart_id_product_variant_id UNIQUE (cart_id, product_variant_id),
    CONSTRAINT fk_cart_items_cart_id FOREIGN KEY (cart_id) REFERENCES carts(id) ON DELETE CASCADE,
    CONSTRAINT fk_cart_items_product_id FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE RESTRICT,
    CONSTRAINT fk_cart_items_product_variant_id FOREIGN KEY (product_variant_id) REFERENCES product_variants(id) ON DELETE RESTRICT,
    CONSTRAINT ck_cart_items_quantity CHECK (quantity BETWEEN 1 AND 1000),
    CONSTRAINT ck_cart_items_public_product_name_nonblank CHECK (public_product_name ~ '[^[:space:]]'),
    CONSTRAINT ck_cart_items_public_sku_nonblank CHECK (public_sku ~ '[^[:space:]]'),
    CONSTRAINT ck_cart_items_public_options_object CHECK (JSONB_TYPEOF(public_options) = 'object')
);
CREATE INDEX idx_cart_items_cart_id_added_at_id ON cart_items(cart_id, added_at DESC, id ASC);
CREATE INDEX idx_cart_items_product_id ON cart_items(product_id);
CREATE INDEX idx_cart_items_product_variant_id ON cart_items(product_variant_id);
