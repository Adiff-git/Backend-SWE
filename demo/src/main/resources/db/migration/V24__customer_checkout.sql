CREATE FUNCTION checkout_money_is_valid(value JSONB) RETURNS BOOLEAN
LANGUAGE SQL IMMUTABLE AS $$
    SELECT COALESCE(JSONB_TYPEOF(value) = 'object'
        AND value - ARRAY['amount','currency'] = '{}'::JSONB
        AND value->>'currency' = 'VND' AND JSONB_TYPEOF(value->'amount') = 'number'
        AND (value->>'amount')::NUMERIC >= 0
        AND TRUNC((value->>'amount')::NUMERIC) = (value->>'amount')::NUMERIC, FALSE);
$$;

CREATE FUNCTION checkout_receipt_is_valid(body JSONB) RETURNS BOOLEAN
LANGUAGE PLPGSQL IMMUTABLE AS $$
DECLARE
    header JSONB;
    item JSONB;
    skipped JSONB;
    previous_id BIGINT := 0;
    current_id BIGINT;
    quantity_value NUMERIC;
    total NUMERIC := 0;
BEGIN
    IF JSONB_TYPEOF(body) IS DISTINCT FROM 'object'
        OR body - ARRAY['order','skippedItems'] <> '{}'::JSONB
        OR JSONB_TYPEOF(body->'order') IS DISTINCT FROM 'object'
        OR JSONB_TYPEOF(body->'skippedItems') IS DISTINCT FROM 'array' THEN RETURN FALSE; END IF;
    header := body->'order';
    IF header - ARRAY['id','orderNumber','placedAt','status','recipientNameSnapshot','recipientPhoneSnapshot','deliveryAddressSnapshot','items','merchandiseTotal','payableTotal'] <> '{}'::JSONB
        OR JSONB_TYPEOF(header->'id') IS DISTINCT FROM 'number'
        OR (header->>'id') !~ '^[1-9][0-9]*$' OR (header->>'id')::BIGINT <= 0
        OR header->>'status' IS DISTINCT FROM 'PENDING'
        OR JSONB_TYPEOF(header->'items') IS DISTINCT FROM 'array'
        OR JSONB_ARRAY_LENGTH(header->'items') = 0
        OR NOT checkout_money_is_valid(header->'merchandiseTotal')
        OR NOT checkout_money_is_valid(header->'payableTotal') THEN RETURN FALSE; END IF;
    FOREACH item IN ARRAY ARRAY[header->'orderNumber',header->'placedAt',header->'recipientNameSnapshot',header->'recipientPhoneSnapshot',header->'deliveryAddressSnapshot'] LOOP
        IF JSONB_TYPEOF(item) IS DISTINCT FROM 'string' OR (item #>> '{}') !~ '[^[:space:]]' THEN RETURN FALSE; END IF;
    END LOOP;
    PERFORM (header->>'placedAt')::TIMESTAMPTZ;
    FOR item IN SELECT value FROM JSONB_ARRAY_ELEMENTS(header->'items') LOOP
        IF JSONB_TYPEOF(item) IS DISTINCT FROM 'object'
            OR item - ARRAY['id','productNameSnapshot','variantSkuSnapshot','variantOptionsSnapshot','quantity','unitPriceSnapshot','lineTotal'] <> '{}'::JSONB
            OR JSONB_TYPEOF(item->'id') IS DISTINCT FROM 'number'
            OR (item->>'id') !~ '^[1-9][0-9]*$'
            OR JSONB_TYPEOF(item->'productNameSnapshot') IS DISTINCT FROM 'string'
            OR (item->>'productNameSnapshot') !~ '[^[:space:]]'
            OR JSONB_TYPEOF(item->'variantSkuSnapshot') IS DISTINCT FROM 'string'
            OR (item->>'variantSkuSnapshot') !~ '[^[:space:]]'
            OR NOT COALESCE(order_options_are_strings(item->'variantOptionsSnapshot'), FALSE)
            OR JSONB_TYPEOF(item->'quantity') IS DISTINCT FROM 'number'
            OR NOT checkout_money_is_valid(item->'unitPriceSnapshot')
            OR NOT checkout_money_is_valid(item->'lineTotal') THEN RETURN FALSE; END IF;
        current_id := (item->>'id')::BIGINT;
        IF current_id <= previous_id THEN RETURN FALSE; END IF;
        previous_id := current_id;
        quantity_value := (item->>'quantity')::NUMERIC;
        IF quantity_value NOT BETWEEN 1 AND 999 OR TRUNC(quantity_value) <> quantity_value
            OR (item->'lineTotal'->>'amount')::NUMERIC <> quantity_value * (item->'unitPriceSnapshot'->>'amount')::NUMERIC THEN RETURN FALSE; END IF;
        total := total + (item->'lineTotal'->>'amount')::NUMERIC;
    END LOOP;
    IF total <> (header->'merchandiseTotal'->>'amount')::NUMERIC
        OR total <> (header->'payableTotal'->>'amount')::NUMERIC THEN RETURN FALSE; END IF;
    previous_id := 0;
    FOR skipped IN SELECT value FROM JSONB_ARRAY_ELEMENTS(body->'skippedItems') LOOP
        IF JSONB_TYPEOF(skipped) IS DISTINCT FROM 'object'
            OR skipped - ARRAY['cartItemId','reason'] <> '{}'::JSONB
            OR JSONB_TYPEOF(skipped->'cartItemId') IS DISTINCT FROM 'number'
            OR (skipped->>'cartItemId') !~ '^[1-9][0-9]*$'
            OR JSONB_TYPEOF(skipped->'reason') IS DISTINCT FROM 'string'
            OR skipped->>'reason' NOT IN ('VARIANT_UNAVAILABLE','PRODUCT_UNAVAILABLE','PRODUCT_NOT_FOR_SALE','INVALID_QUANTITY','INVALID_PRICE') THEN RETURN FALSE; END IF;
        current_id := (skipped->>'cartItemId')::BIGINT;
        IF current_id <= previous_id THEN RETURN FALSE; END IF;
        previous_id := current_id;
    END LOOP;
    RETURN TRUE;
EXCEPTION WHEN OTHERS THEN RETURN FALSE;
END;
$$;

CREATE TABLE checkout_receipts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    operation TEXT NOT NULL,
    idempotency_key VARCHAR(128) COLLATE "C" NOT NULL,
    request_address_id BIGINT NOT NULL,
    request_fingerprint TEXT NOT NULL,
    order_id BIGINT NOT NULL,
    receipt_version INTEGER NOT NULL,
    response_status INTEGER NOT NULL,
    location TEXT NOT NULL,
    receipt_body JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_checkout_receipts_customer_id_operation_idempotency_key UNIQUE (customer_id, operation, idempotency_key),
    CONSTRAINT uk_checkout_receipts_order_id UNIQUE (order_id),
    CONSTRAINT fk_checkout_receipts_customer_id FOREIGN KEY (customer_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT fk_checkout_receipts_order_id_customer_id FOREIGN KEY (order_id, customer_id) REFERENCES orders(id, customer_id) ON DELETE RESTRICT,
    CONSTRAINT ck_checkout_receipts_key CHECK (idempotency_key ~ '^[A-Za-z0-9_-]{16,128}$'),
    CONSTRAINT ck_checkout_receipts_operation CHECK (operation = 'CHECKOUT'),
    CONSTRAINT ck_checkout_receipts_address CHECK (request_address_id > 0),
    CONSTRAINT ck_checkout_receipts_fingerprint CHECK (request_fingerprint ~ '^[a-f0-9]{64}$'),
    CONSTRAINT ck_checkout_receipts_version CHECK (receipt_version = 1),
    CONSTRAINT ck_checkout_receipts_status CHECK (response_status = 201),
    CONSTRAINT ck_checkout_receipts_location CHECK (location = '/api/me/orders/' || order_id),
    CONSTRAINT ck_checkout_receipts_body CHECK (checkout_receipt_is_valid(receipt_body)
        AND (receipt_body->'order'->>'id')::BIGINT = order_id
        AND (receipt_body->'order'->>'placedAt')::TIMESTAMPTZ = created_at)
);

CREATE FUNCTION reject_checkout_receipt_update() RETURNS TRIGGER LANGUAGE PLPGSQL AS $$
BEGIN
    RAISE EXCEPTION 'Checkout receipt is immutable' USING ERRCODE = '23514';
END;
$$;
CREATE TRIGGER ct_checkout_receipts_immutable BEFORE UPDATE ON checkout_receipts
    FOR EACH ROW EXECUTE FUNCTION reject_checkout_receipt_update();

CREATE FUNCTION check_checkout_receipt_integrity() RETURNS TRIGGER LANGUAGE PLPGSQL AS $$
DECLARE
    original JSONB;
BEGIN
    SELECT JSONB_BUILD_OBJECT('id', o.id, 'orderNumber', o.order_number, 'status', o.status,
        'recipientNameSnapshot',o.recipient_name_snapshot, 'recipientPhoneSnapshot',o.recipient_phone_snapshot,
        'deliveryAddressSnapshot',o.delivery_address_snapshot,
        'merchandiseTotal',JSONB_BUILD_OBJECT('amount',o.merchandise_total,'currency','VND'),
        'payableTotal',JSONB_BUILD_OBJECT('amount',o.payable_total,'currency','VND'),
        'items',(SELECT JSONB_AGG(JSONB_BUILD_OBJECT('id',i.id,'productNameSnapshot',i.product_name_snapshot,
            'variantSkuSnapshot',i.variant_sku_snapshot,'variantOptionsSnapshot',i.variant_options_snapshot,
            'quantity',i.quantity,'unitPriceSnapshot',JSONB_BUILD_OBJECT('amount',i.unit_price_snapshot,'currency','VND'),
            'lineTotal',JSONB_BUILD_OBJECT('amount',i.line_total,'currency','VND')) ORDER BY i.id)
            FROM order_items i WHERE i.order_id=o.id)) INTO original
        FROM orders o WHERE o.id=NEW.order_id AND o.customer_id=NEW.customer_id AND o.placed_at=NEW.created_at;
    IF original IS NULL OR original <> (NEW.receipt_body->'order') - 'placedAt' THEN
        RAISE EXCEPTION 'Checkout receipt does not match original order' USING ERRCODE = '23514', CONSTRAINT = 'ct_checkout_receipts_integrity';
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER ct_checkout_receipts_integrity AFTER INSERT ON checkout_receipts
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_checkout_receipt_integrity();

