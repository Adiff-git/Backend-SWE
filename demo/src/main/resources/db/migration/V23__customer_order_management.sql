CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    order_number TEXT NOT NULL,
    placed_at TIMESTAMPTZ NOT NULL,
    status TEXT NOT NULL,
    recipient_name_snapshot TEXT NOT NULL,
    recipient_phone_snapshot TEXT NOT NULL,
    delivery_address_snapshot TEXT NOT NULL,
    merchandise_total NUMERIC NOT NULL,
    payable_total NUMERIC NOT NULL,
    cancelled_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    cancellation_reason TEXT,
    CONSTRAINT fk_orders_customer_id FOREIGN KEY (customer_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT uk_orders_order_number UNIQUE (order_number),
    CONSTRAINT ck_orders_number CHECK (order_number ~ '[^[:space:]]'),
    CONSTRAINT ck_orders_recipient CHECK (recipient_name_snapshot ~ '[^[:space:]]' AND recipient_phone_snapshot ~ '[^[:space:]]' AND delivery_address_snapshot ~ '[^[:space:]]'),
    CONSTRAINT ck_orders_status CHECK (status IN ('PENDING','CONFIRMED','SHIPPING','COMPLETED','CANCELLED')),
    CONSTRAINT ck_orders_terminal_times CHECK (
        (status = 'CANCELLED') = (cancelled_at IS NOT NULL)
        AND (status = 'COMPLETED') = (completed_at IS NOT NULL)
        AND (cancelled_at IS NULL OR cancelled_at >= placed_at)
        AND (completed_at IS NULL OR completed_at >= placed_at)),
    CONSTRAINT ck_orders_reason CHECK (cancellation_reason IS NULL OR
        (status = 'CANCELLED' AND CHAR_LENGTH(cancellation_reason) BETWEEN 1 AND 500
        AND cancellation_reason ~ '[^[:space:]]' AND cancellation_reason !~ '^[[:space:]]|[[:space:]]$')),
    CONSTRAINT ck_orders_merchandise CHECK (merchandise_total::TEXT NOT IN ('NaN','Infinity','-Infinity') AND merchandise_total >= 0 AND TRUNC(merchandise_total) = merchandise_total),
    CONSTRAINT ck_orders_payable CHECK (payable_total::TEXT NOT IN ('NaN','Infinity','-Infinity') AND payable_total >= 0 AND TRUNC(payable_total) = payable_total)
);

CREATE FUNCTION order_options_are_strings(options JSONB) RETURNS BOOLEAN
LANGUAGE SQL IMMUTABLE STRICT AS $$
    SELECT CASE WHEN JSONB_TYPEOF(options) = 'object' THEN
        NOT EXISTS (SELECT 1 FROM JSONB_EACH(options) AS entry WHERE JSONB_TYPEOF(entry.value) <> 'string')
        ELSE FALSE END;
$$;

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    product_id UUID,
    product_variant_id UUID,
    product_name_snapshot TEXT NOT NULL,
    variant_sku_snapshot TEXT NOT NULL,
    variant_options_snapshot JSONB NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price_snapshot NUMERIC NOT NULL,
    line_total NUMERIC NOT NULL,
    CONSTRAINT fk_order_items_order_id FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT,
    CONSTRAINT fk_order_items_product_id FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE SET NULL,
    CONSTRAINT fk_order_items_product_variant_id FOREIGN KEY (product_variant_id) REFERENCES product_variants(id) ON DELETE SET NULL,
    CONSTRAINT ck_order_items_names CHECK (product_name_snapshot ~ '[^[:space:]]' AND variant_sku_snapshot ~ '[^[:space:]]'),
    CONSTRAINT ck_order_items_options CHECK (order_options_are_strings(variant_options_snapshot)),
    CONSTRAINT ck_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_items_price CHECK (unit_price_snapshot::TEXT NOT IN ('NaN','Infinity','-Infinity') AND unit_price_snapshot >= 0 AND TRUNC(unit_price_snapshot) = unit_price_snapshot),
    CONSTRAINT ck_order_items_line CHECK (line_total::TEXT NOT IN ('NaN','Infinity','-Infinity') AND line_total >= 0 AND TRUNC(line_total) = line_total AND line_total = unit_price_snapshot * quantity)
);

CREATE INDEX idx_orders_customer_id_placed_at_id ON orders(customer_id, placed_at DESC, id ASC);
CREATE INDEX idx_orders_customer_id_status_placed_at_id ON orders(customer_id, status, placed_at DESC, id ASC);
CREATE INDEX idx_orders_customer_id_payable_total_id ON orders(customer_id, payable_total DESC, id ASC);
CREATE INDEX idx_orders_customer_id_status_payable_total_id ON orders(customer_id, status, payable_total DESC, id ASC);
CREATE INDEX idx_order_items_order_id_id ON order_items(order_id, id ASC);
CREATE INDEX idx_order_items_product_id ON order_items(product_id);
CREATE INDEX idx_order_items_product_variant_id ON order_items(product_variant_id);

-- Deferred validation permits complete parent/children fixture insertion in one transaction.
-- It never writes totals or snapshots. Independent future item writers must coordinate parents.
CREATE FUNCTION check_order_item_integrity() RETURNS TRIGGER LANGUAGE PLPGSQL AS $$
DECLARE
    affected_ids BIGINT[];
    affected_id BIGINT;
    expected_total NUMERIC;
    actual_total NUMERIC;
    item_count BIGINT;
BEGIN
    IF TG_TABLE_NAME = 'orders' THEN
        affected_ids := ARRAY[NEW.id];
    ELSIF TG_OP = 'INSERT' THEN
        affected_ids := ARRAY[NEW.order_id];
    ELSIF TG_OP = 'DELETE' THEN
        affected_ids := ARRAY[OLD.order_id];
    ELSE
        affected_ids := ARRAY[OLD.order_id, NEW.order_id];
    END IF;
    FOR affected_id IN SELECT DISTINCT a.id FROM UNNEST(affected_ids) AS a(id) ORDER BY a.id LOOP
        SELECT merchandise_total INTO expected_total FROM orders WHERE id = affected_id FOR NO KEY UPDATE;
        IF NOT FOUND THEN CONTINUE; END IF;
        SELECT COUNT(*), COALESCE(SUM(line_total), 0) INTO item_count, actual_total FROM order_items WHERE order_id = affected_id;
        IF item_count = 0 OR actual_total <> expected_total THEN
            RAISE EXCEPTION 'Order items do not match historical merchandise total'
                USING ERRCODE = '23514', CONSTRAINT = 'ct_orders_item_integrity';
        END IF;
    END LOOP;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER ct_orders_item_integrity AFTER INSERT OR UPDATE ON orders
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_order_item_integrity();
CREATE CONSTRAINT TRIGGER ct_order_items_integrity AFTER INSERT OR UPDATE OR DELETE ON order_items
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_order_item_integrity();

