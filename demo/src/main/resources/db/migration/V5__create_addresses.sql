CREATE TABLE addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_name VARCHAR(100) NOT NULL,
    recipient_phone VARCHAR(10) NOT NULL,
    address_text VARCHAR(1000) NOT NULL,
    is_default BOOLEAN NOT NULL,
    user_id BIGINT NOT NULL,
    CONSTRAINT fk_addresses_user_id FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT ck_addresses_recipient_name_nonblank CHECK (recipient_name ~ '[^[:space:]]'),
    CONSTRAINT ck_addresses_address_text_nonblank CHECK (address_text ~ '[^[:space:]]'),
    CONSTRAINT ck_addresses_recipient_phone CHECK (recipient_phone ~ '^0[0-9]{9}$')
);

CREATE INDEX idx_addresses_user_id_is_default_id
    ON addresses (user_id, is_default DESC, id DESC);
CREATE UNIQUE INDEX idx_addresses_user_id_default
    ON addresses (user_id) WHERE is_default;
