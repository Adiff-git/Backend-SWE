CREATE TABLE product_reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_item_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    product_id UUID NOT NULL,
    rating SMALLINT NOT NULL,
    comment TEXT,
    created_at TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_product_reviews_order_item_id UNIQUE (order_item_id),
    CONSTRAINT fk_product_reviews_order_item_id FOREIGN KEY (order_item_id) REFERENCES order_items(id) ON DELETE RESTRICT,
    CONSTRAINT fk_product_reviews_author_id FOREIGN KEY (author_id) REFERENCES users(id) ON DELETE RESTRICT,
    CONSTRAINT ck_product_reviews_rating CHECK (rating BETWEEN 1 AND 5),
    CONSTRAINT ck_product_reviews_comment_length CHECK (CHAR_LENGTH(comment) <= 2000),
    CONSTRAINT ck_product_reviews_timestamps CHECK (updated_at >= created_at)
);
CREATE INDEX idx_product_reviews_product_id_created_at_id ON product_reviews(product_id, created_at DESC, id DESC);
CREATE INDEX idx_product_reviews_product_id_rating_id ON product_reviews(product_id, rating, id DESC);
CREATE TABLE product_review_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    review_id BIGINT NOT NULL,
    image_id UUID NOT NULL,
    display_order INTEGER NOT NULL,
    CONSTRAINT fk_product_review_images_review_id FOREIGN KEY (review_id) REFERENCES product_reviews(id) ON DELETE CASCADE,
    CONSTRAINT fk_product_review_images_image_id FOREIGN KEY (image_id) REFERENCES image_uploads(id) ON DELETE RESTRICT,
    CONSTRAINT uk_product_review_images_review_id_display_order UNIQUE (review_id, display_order),
    CONSTRAINT uk_product_review_images_review_id_image_id UNIQUE (review_id, image_id),
    CONSTRAINT ck_product_review_images_display_order CHECK (display_order >= 0 AND display_order < 10)
);
