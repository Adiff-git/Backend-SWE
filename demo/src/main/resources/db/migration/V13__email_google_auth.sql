);
CREATE INDEX idx_oauth_handoffs_expires_at ON oauth_handoffs(expires_at);

CREATE TABLE email_verification_challenges (
    id UUID PRIMARY KEY,
    user_id BIGINT REFERENCES users(id),
    pending_registration_id UUID REFERENCES pending_registrations(id),
    generation INTEGER NOT NULL CHECK (generation >= 1),
    destination VARCHAR(254) NOT NULL CHECK (destination = LOWER(destination) AND LENGTH(TRIM(destination)) > 0),
    purpose VARCHAR(32) NOT NULL CHECK (purpose IN ('REGISTRATION','EMAIL_CHANGE')),
    code_mac BYTEA CHECK (OCTET_LENGTH(code_mac) = 32),
    key_id VARCHAR(32) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    failed_attempts SMALLINT NOT NULL DEFAULT 0 CHECK (failed_attempts BETWEEN 0 AND 5),
    active BOOLEAN NOT NULL,
    consumed_at TIMESTAMPTZ,
    superseded_at TIMESTAMPTZ,
    delivery_status VARCHAR(16) NOT NULL CHECK (delivery_status IN ('QUEUED','SENT','FAILED','EXPIRED')),
    CONSTRAINT ck_email_verification_challenges_owner CHECK ((user_id IS NULL) <> (pending_registration_id IS NULL)),
    CONSTRAINT ck_email_verification_challenges_purpose CHECK (pending_registration_id IS NULL OR purpose = 'REGISTRATION'),
    CONSTRAINT ck_email_verification_challenges_expiry CHECK (expires_at = created_at + INTERVAL '10 minutes'),
    CONSTRAINT ck_email_verification_challenges_active CHECK (NOT active OR (code_mac IS NOT NULL AND consumed_at IS NULL AND superseded_at IS NULL AND failed_attempts < 5))
);
CREATE UNIQUE INDEX uk_email_verification_challenges_user_purpose_active ON email_verification_challenges(user_id,purpose) WHERE active AND user_id IS NOT NULL;
CREATE UNIQUE INDEX uk_email_verification_challenges_pending_purpose_active ON email_verification_challenges(pending_registration_id,purpose) WHERE active AND pending_registration_id IS NOT NULL;
CREATE INDEX idx_email_verification_challenges_expires_at ON email_verification_challenges(expires_at);
CREATE TABLE verification_mail_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_id UUID NOT NULL REFERENCES email_verification_challenges(id),
    rate_reservation_id UUID NOT NULL REFERENCES rate_limit_reservations(id),
    encrypted_payload BYTEA,
    nonce BYTEA,
    key_id VARCHAR(32) NOT NULL,
    state VARCHAR(16) NOT NULL CHECK (state IN ('PENDING','LEASED','SENT','FAILED','EXPIRED')),
    attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count BETWEEN 0 AND 4),
    next_attempt_at TIMESTAMPTZ NOT NULL,
    lease_until TIMESTAMPTZ,
    expires_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_verification_mail_outbox_rate_reservation_id UNIQUE (rate_reservation_id),
    CONSTRAINT ck_verification_mail_outbox_payload CHECK (state NOT IN ('PENDING','LEASED') OR (encrypted_payload IS NOT NULL AND OCTET_LENGTH(nonce) = 12))
);
CREATE INDEX idx_verification_mail_outbox_state_next_attempt_at ON verification_mail_outbox(state,next_attempt_at);
CREATE INDEX idx_verification_mail_outbox_challenge_id ON verification_mail_outbox(challenge_id);
CREATE INDEX idx_oauth_login_attempts_browser_slot_id ON oauth_login_attempts(browser_slot_id,browser_binding_hash,expires_at);

