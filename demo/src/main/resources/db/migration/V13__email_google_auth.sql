CREATE TABLE pending_registrations (
    id UUID PRIMARY KEY,
    destination VARCHAR(254) NOT NULL,
    credential_hash BYTEA,
    generation INTEGER NOT NULL CHECK (generation >= 1),
    state VARCHAR(16) NOT NULL CHECK (state IN ('ACTIVE','CONFIRMED','CONFLICT','EXPIRED')),
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    expired_at TIMESTAMPTZ,
    CONSTRAINT uk_pending_registrations_credential_hash UNIQUE (credential_hash),
    CONSTRAINT ck_pending_registrations_credential CHECK ((state <> 'ACTIVE' OR credential_hash IS NOT NULL) AND (credential_hash IS NULL OR OCTET_LENGTH(credential_hash) = 32)),
    CONSTRAINT ck_pending_registrations_destination CHECK (destination = LOWER(destination) AND LENGTH(TRIM(destination)) > 0),
    CONSTRAINT ck_pending_registrations_expiry CHECK (expires_at > created_at)
);
CREATE INDEX idx_pending_registrations_expires_at ON pending_registrations(expires_at);
CREATE INDEX idx_pending_registrations_destination ON pending_registrations(destination);

CREATE TABLE google_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    provider VARCHAR(16) NOT NULL CHECK (provider = 'GOOGLE'),
    issuer TEXT NOT NULL CHECK (issuer = 'https://accounts.google.com'),
    subject TEXT NOT NULL CHECK (LENGTH(TRIM(subject)) > 0),
    provider_email VARCHAR(254),
    linked_at TIMESTAMPTZ NOT NULL,
    last_successful_login_at TIMESTAMPTZ,
    CONSTRAINT uk_google_identities_provider_issuer_subject UNIQUE (provider,issuer,subject),
    CONSTRAINT uk_google_identities_user_id_provider UNIQUE (user_id,provider)
);

CREATE TABLE recent_auth_proofs (
    id UUID PRIMARY KEY,
    secret_hash BYTEA NOT NULL CHECK (OCTET_LENGTH(secret_hash) = 32),
    owner_user_id BIGINT NOT NULL REFERENCES users(id),
    initiating_session_id UUID NOT NULL REFERENCES authentication_sessions(id),
    method VARCHAR(16) NOT NULL CHECK (method IN ('PASSWORD','GOOGLE')),
    operation VARCHAR(32) NOT NULL CHECK (operation IN ('EMAIL_CHANGE','INITIAL_PASSWORD','CONNECT_GOOGLE')),
    provider_identity_id BIGINT REFERENCES google_identities(id),
    authenticated_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    CONSTRAINT uk_recent_auth_proofs_secret_hash UNIQUE (secret_hash),
    CONSTRAINT ck_recent_auth_proofs_expiry CHECK (expires_at = authenticated_at + INTERVAL '5 minutes'),
    CONSTRAINT ck_recent_auth_proofs_method CHECK ((method = 'GOOGLE') = (provider_identity_id IS NOT NULL)),
    CONSTRAINT ck_recent_auth_proofs_initial_password CHECK (operation <> 'INITIAL_PASSWORD' OR method = 'GOOGLE')
);
CREATE INDEX idx_recent_auth_proofs_expires_at ON recent_auth_proofs(expires_at);
CREATE INDEX idx_recent_auth_proofs_initiating_session_id ON recent_auth_proofs(initiating_session_id);

CREATE TABLE rate_limit_buckets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    policy VARCHAR(32) NOT NULL CHECK (policy IN ('GOOGLE_INIT','HANDOFF_FAILURE','LOCAL_REAUTH_FAILURE','OTP_OWNER','OTP_DESTINATION')),
    dimension VARCHAR(16) NOT NULL CHECK (dimension IN ('IP','USER','PENDING','DESTINATION')),
    key_digest BYTEA NOT NULL CHECK (OCTET_LENGTH(key_digest) = 32),
    CONSTRAINT uk_rate_limit_buckets_policy_dimension_key_digest UNIQUE (policy,dimension,key_digest),
    CONSTRAINT ck_rate_limit_buckets_dimension CHECK ((policy IN ('GOOGLE_INIT','HANDOFF_FAILURE') AND dimension = 'IP') OR (policy = 'LOCAL_REAUTH_FAILURE' AND dimension = 'USER') OR (policy = 'OTP_OWNER' AND dimension IN ('USER','PENDING')) OR (policy = 'OTP_DESTINATION' AND dimension = 'DESTINATION'))
);
CREATE TABLE rate_limit_reservations (
    id UUID PRIMARY KEY,
    policy_family VARCHAR(32) NOT NULL CHECK (policy_family IN ('GOOGLE_INIT','HANDOFF_FAILURE','LOCAL_REAUTH_FAILURE','OTP_SEND')),
    operation_kind VARCHAR(32) NOT NULL CHECK (operation_kind IN ('GOOGLE_INIT','EXCHANGE','LOCAL_REAUTH','PENDING_INITIAL','PENDING_RESEND','USER_EMAIL_SEND')),
    state VARCHAR(16) NOT NULL CHECK (state IN ('RESERVED','COUNTED','RELEASED')),
    admitted_at TIMESTAMPTZ NOT NULL,
    request_deadline TIMESTAMPTZ NOT NULL,
    lease_until TIMESTAMPTZ NOT NULL,
    finalized_at TIMESTAMPTZ,
    CONSTRAINT ck_rate_limit_reservations_deadlines CHECK (request_deadline = admitted_at + INTERVAL '30 seconds' AND lease_until = admitted_at + INTERVAL '35 seconds'),
    CONSTRAINT ck_rate_limit_reservations_finalization CHECK ((state = 'RESERVED') = (finalized_at IS NULL))
);
CREATE INDEX idx_rate_limit_reservations_state_lease_until ON rate_limit_reservations(state,lease_until);
CREATE TABLE rate_limit_operations (
    id UUID PRIMARY KEY REFERENCES rate_limit_reservations(id),
    status VARCHAR(16) NOT NULL CHECK (status IN ('OPEN','COMMITTED','ABORTED')),
    outcome VARCHAR(16) CHECK (outcome IN ('ACCEPTED','SUCCESS','FAILURE')),
    business_kind VARCHAR(32) NOT NULL,
    pending_registration_id UUID,
    challenge_id UUID,
    outbox_id BIGINT,
    attempt_id UUID,
    completed_at TIMESTAMPTZ,
    receipt_version INTEGER NOT NULL DEFAULT 1 CHECK (receipt_version = 1),
    CONSTRAINT ck_rate_limit_operations_completion CHECK ((status = 'OPEN' AND outcome IS NULL AND completed_at IS NULL) OR (status = 'COMMITTED' AND outcome IS NOT NULL AND completed_at IS NOT NULL) OR (status = 'ABORTED' AND outcome IS NULL AND completed_at IS NOT NULL))
);
CREATE TABLE rate_limit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bucket_id BIGINT NOT NULL REFERENCES rate_limit_buckets(id),
    reservation_id UUID NOT NULL REFERENCES rate_limit_reservations(id),
    admitted_at TIMESTAMPTZ NOT NULL,
    state VARCHAR(16) NOT NULL CHECK (state IN ('RESERVED','COUNTED')),
    CONSTRAINT uk_rate_limit_events_bucket_id_reservation_id UNIQUE (bucket_id,reservation_id)
);
CREATE INDEX idx_rate_limit_events_bucket_id_admitted_at_id ON rate_limit_events(bucket_id,admitted_at,id);
CREATE INDEX idx_rate_limit_events_reservation_id ON rate_limit_events(reservation_id);

CREATE TABLE oauth_browser_slots (
    id UUID PRIMARY KEY,
    slot_secret_hash BYTEA NOT NULL CHECK (OCTET_LENGTH(slot_secret_hash) = 32),
    generation INTEGER NOT NULL CHECK (generation >= 1),
    current_attempt_id UUID,
    expires_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_oauth_browser_slots_slot_secret_hash UNIQUE (slot_secret_hash),
    CONSTRAINT uk_oauth_browser_slots_current_attempt_id UNIQUE (current_attempt_id)
);
CREATE INDEX idx_oauth_browser_slots_expires_at ON oauth_browser_slots(expires_at);
CREATE TABLE oauth_login_attempts (
    id UUID PRIMARY KEY,
    start_ticket_hash BYTEA CHECK (OCTET_LENGTH(start_ticket_hash) = 32),
    purpose VARCHAR(16) NOT NULL CHECK (purpose IN ('LOGIN','LINK','REAUTH')),
    operation VARCHAR(32) CHECK (operation IN ('EMAIL_CHANGE','INITIAL_PASSWORD','CONNECT_GOOGLE')),
    owner_user_id BIGINT REFERENCES users(id),
    initiating_session_id UUID REFERENCES authentication_sessions(id),
    recent_auth_proof_id UUID REFERENCES recent_auth_proofs(id),
    destination_key VARCHAR(32) NOT NULL,
    pkce_challenge CHAR(43) NOT NULL,
    browser_slot_id UUID NOT NULL REFERENCES oauth_browser_slots(id),
    browser_generation INTEGER NOT NULL CHECK (browser_generation >= 1),
    browser_binding_hash BYTEA NOT NULL CHECK (OCTET_LENGTH(browser_binding_hash) = 32),
    oauth_state_hash BYTEA CHECK (OCTET_LENGTH(oauth_state_hash) = 32),
    encrypted_request BYTEA,
    encryption_key_id VARCHAR(32),
    nonce BYTEA,
    status VARCHAR(32) NOT NULL CHECK (status IN ('CREATED','STARTED','CALLBACK_VALIDATED','FAILED','EXPIRED')),
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    rate_reservation_id UUID REFERENCES rate_limit_reservations(id),
    CONSTRAINT uk_oauth_login_attempts_start_ticket_hash UNIQUE (start_ticket_hash),
    CONSTRAINT uk_oauth_login_attempts_oauth_state_hash UNIQUE (oauth_state_hash),
    CONSTRAINT ck_oauth_login_attempts_expiry CHECK (expires_at = created_at + INTERVAL '5 minutes'),
    CONSTRAINT ck_oauth_login_attempts_owner CHECK ((purpose = 'LOGIN' AND owner_user_id IS NULL AND initiating_session_id IS NULL AND operation IS NULL AND recent_auth_proof_id IS NULL) OR (purpose = 'REAUTH' AND owner_user_id IS NOT NULL AND initiating_session_id IS NOT NULL AND operation IS NOT NULL AND recent_auth_proof_id IS NULL) OR (purpose = 'LINK' AND owner_user_id IS NOT NULL AND initiating_session_id IS NOT NULL AND operation = 'CONNECT_GOOGLE' AND recent_auth_proof_id IS NOT NULL))
);
ALTER TABLE oauth_browser_slots ADD CONSTRAINT fk_oauth_browser_slots_current_attempt FOREIGN KEY (current_attempt_id) REFERENCES oauth_login_attempts(id) DEFERRABLE INITIALLY DEFERRED;
CREATE INDEX idx_oauth_login_attempts_expires_at ON oauth_login_attempts(expires_at);
