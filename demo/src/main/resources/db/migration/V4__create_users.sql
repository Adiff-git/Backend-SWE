CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name VARCHAR(100),
    username VARCHAR(50) NOT NULL,
    username_key TEXT GENERATED ALWAYS AS (LOWER(username)) STORED NOT NULL,
    password TEXT NOT NULL,
    email VARCHAR(254),
    email_key TEXT GENERATED ALWAYS AS (LOWER(email)) STORED,
    phone_number VARCHAR(20),
    account_status VARCHAR(16) NOT NULL,
    gender VARCHAR(6),
    date_of_birth DATE,
    joined_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_users_username_key UNIQUE (username_key),
    CONSTRAINT uk_users_email_key UNIQUE (email_key),
    CONSTRAINT ck_users_username_nonblank CHECK (username ~ '[^[:space:]]'),
    CONSTRAINT ck_users_password_nonblank CHECK (password ~ '[^[:space:]]'),
    CONSTRAINT ck_users_display_name_nonblank CHECK (display_name IS NULL OR display_name ~ '[^[:space:]]'),
    CONSTRAINT ck_users_email_nonblank CHECK (email IS NULL OR email ~ '[^[:space:]]'),
    CONSTRAINT ck_users_email_lowercase CHECK (email IS NULL OR email = LOWER(email)),
    CONSTRAINT ck_users_phone_number_nonblank CHECK (phone_number IS NULL OR phone_number ~ '[^[:space:]]'),
    CONSTRAINT ck_users_account_status CHECK (account_status IN ('ACTIVE', 'INACTIVE', 'SUSPENDED', 'BANNED')),
    CONSTRAINT ck_users_gender CHECK (gender IS NULL OR gender IN ('MALE', 'FEMALE', 'OTHER'))
);
