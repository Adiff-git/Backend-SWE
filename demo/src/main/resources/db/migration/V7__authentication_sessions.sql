CREATE TABLE authentication_sessions (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    revocation_reason VARCHAR(32),
    CONSTRAINT ck_authentication_sessions_expiry CHECK (expires_at = created_at + INTERVAL '604800 seconds'),
    CONSTRAINT ck_authentication_sessions_revocation CHECK ((revoked_at IS NULL AND revocation_reason IS NULL) OR (revoked_at IS NOT NULL AND revocation_reason IS NOT NULL AND revocation_reason IN ('LOGOUT','REFRESH_REUSE','PASSWORD_CHANGED')))
);
CREATE INDEX idx_authentication_sessions_user_id_id ON authentication_sessions(user_id,id);
CREATE INDEX idx_authentication_sessions_expires_at ON authentication_sessions(expires_at);
CREATE TABLE refresh_credentials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id UUID NOT NULL REFERENCES authentication_sessions(id),
    token_hash BYTEA NOT NULL,
    issued_at TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    CONSTRAINT uk_refresh_credentials_token_hash UNIQUE(token_hash),
    CONSTRAINT ck_refresh_credentials_hash_length CHECK (OCTET_LENGTH(token_hash)=32)
);
CREATE UNIQUE INDEX idx_refresh_credentials_session_id_current ON refresh_credentials(session_id) WHERE consumed_at IS NULL;
CREATE INDEX idx_refresh_credentials_session_id_id ON refresh_credentials(session_id,id);
