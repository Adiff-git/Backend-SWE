CREATE TABLE wishlist_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    product_id UUID NOT NULL,
    added_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uk_wishlist_items_user_id_product_id UNIQUE (user_id, product_id),
    CONSTRAINT fk_wishlist_items_user_id FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_wishlist_items_product_id FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

CREATE INDEX idx_wishlist_items_user_id_added_at_product_id
    ON wishlist_items (user_id, added_at DESC, product_id ASC);
CREATE INDEX idx_wishlist_items_product_id ON wishlist_items (product_id);

INSERT INTO permissions(name) VALUES ('MANAGE_WISHLIST');
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM roles WHERE name = 'USER') THEN
        RAISE EXCEPTION 'Required default USER role is missing';
    END IF;
END;
$$;
INSERT INTO role_permissions(role_id, permission_id)
    SELECT r.id, p.id FROM roles r CROSS JOIN permissions p
    WHERE r.name = 'USER' AND p.name = 'MANAGE_WISHLIST';
