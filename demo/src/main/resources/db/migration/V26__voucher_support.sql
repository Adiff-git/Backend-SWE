-- Definitions/grants are provisioned externally; no production voucher data is seeded.
CREATE TABLE vouchers (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 code VARCHAR(64) NOT NULL, title TEXT NOT NULL, description TEXT,
 discount_type TEXT NOT NULL, discount_value NUMERIC NOT NULL,
 minimum_subtotal NUMERIC NOT NULL DEFAULT 0, maximum_discount NUMERIC,
 valid_from TIMESTAMPTZ, valid_until TIMESTAMPTZ, enabled BOOLEAN NOT NULL DEFAULT TRUE,
 global_usage_limit BIGINT, per_customer_usage_limit BIGINT, redeemed_count BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT uk_vouchers_code UNIQUE(code),
 CONSTRAINT ck_vouchers_definition CHECK (
  code ~ '^[A-Z0-9_-]{1,64}$' AND title ~ '[^[:space:]]'
  AND discount_value::TEXT NOT IN ('NaN','Infinity','-Infinity') AND discount_value>0
  AND ((discount_type='FIXED_AMOUNT' AND TRUNC(discount_value)=discount_value AND maximum_discount IS NULL)
    OR (discount_type='PERCENTAGE' AND discount_value<=100 AND TRUNC(discount_value,2)=discount_value))
  AND minimum_subtotal::TEXT NOT IN ('NaN','Infinity','-Infinity') AND minimum_subtotal>=0 AND TRUNC(minimum_subtotal)=minimum_subtotal
  AND (maximum_discount IS NULL OR (maximum_discount::TEXT NOT IN ('NaN','Infinity','-Infinity') AND maximum_discount>=0 AND TRUNC(maximum_discount)=maximum_discount))
  AND (valid_from IS NULL OR valid_until IS NULL OR valid_from<valid_until)),
 CONSTRAINT ck_vouchers_usage CHECK (redeemed_count>=0 AND (global_usage_limit IS NULL OR (global_usage_limit>0 AND redeemed_count<=global_usage_limit)) AND (per_customer_usage_limit IS NULL OR per_customer_usage_limit>0))
);
CREATE TABLE voucher_customer_usages (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 voucher_id BIGINT NOT NULL REFERENCES vouchers(id) ON DELETE RESTRICT,
 customer_id BIGINT NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 redeemed_count BIGINT NOT NULL DEFAULT 0,
 CONSTRAINT uk_voucher_customer_usages_voucher_id_customer_id UNIQUE(voucher_id,customer_id),
 CONSTRAINT uk_voucher_customer_usages_identity UNIQUE(id,voucher_id,customer_id),
 CONSTRAINT ck_voucher_usages_count CHECK(redeemed_count>=0)
);
CREATE INDEX idx_voucher_customer_usages_customer_id_voucher_id ON voucher_customer_usages(customer_id,voucher_id);
CREATE TABLE voucher_entitlements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 voucher_customer_usage_id BIGINT NOT NULL, voucher_id BIGINT NOT NULL, customer_id BIGINT NOT NULL,
 granted_at TIMESTAMPTZ NOT NULL, state TEXT NOT NULL DEFAULT 'AVAILABLE', consumed_at TIMESTAMPTZ,
 CONSTRAINT fk_voucher_entitlements_usage FOREIGN KEY(voucher_customer_usage_id,voucher_id,customer_id) REFERENCES voucher_customer_usages(id,voucher_id,customer_id) ON DELETE RESTRICT,
 CONSTRAINT uk_voucher_entitlements_id_customer_id UNIQUE(id,customer_id),
 CONSTRAINT uk_voucher_entitlements_identity UNIQUE(id,voucher_id,customer_id),
 CONSTRAINT uk_voucher_entitlements_usage_identity UNIQUE(id,voucher_customer_usage_id,voucher_id,customer_id),
 CONSTRAINT ck_voucher_entitlements_state CHECK(state IN ('AVAILABLE','CONSUMED') AND (state='AVAILABLE')=(consumed_at IS NULL) AND (consumed_at IS NULL OR consumed_at>=granted_at))
);
CREATE INDEX idx_voucher_entitlements_customer_id_state_id ON voucher_entitlements(customer_id,state,id);
ALTER TABLE carts ADD COLUMN voucher_entitlement_id BIGINT;
ALTER TABLE carts ADD COLUMN voucher_selection_revision BIGINT NOT NULL DEFAULT 0;
ALTER TABLE carts ADD CONSTRAINT ck_carts_voucher_revision CHECK(voucher_selection_revision>=0);
ALTER TABLE carts ADD CONSTRAINT fk_carts_owned_voucher FOREIGN KEY(voucher_entitlement_id,user_id) REFERENCES voucher_entitlements(id,customer_id) ON DELETE RESTRICT;
ALTER TABLE orders ADD COLUMN voucher_discount NUMERIC NOT NULL DEFAULT 0;
ALTER TABLE orders ADD COLUMN voucher_snapshot JSONB;
ALTER TABLE orders ADD CONSTRAINT ck_orders_voucher_totals CHECK(voucher_discount::TEXT NOT IN ('NaN','Infinity','-Infinity') AND voucher_discount>=0 AND TRUNC(voucher_discount)=voucher_discount AND voucher_discount<=merchandise_total AND (payable_total=merchandise_total-voucher_discount OR (NOT inventory_managed AND voucher_snapshot IS NULL AND voucher_discount=0)) AND (voucher_snapshot IS NOT NULL OR voucher_discount=0));
CREATE TABLE voucher_redemptions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 voucher_id BIGINT NOT NULL REFERENCES vouchers(id) ON DELETE RESTRICT,
 voucher_entitlement_id BIGINT NOT NULL, voucher_customer_usage_id BIGINT NOT NULL,
 customer_id BIGINT NOT NULL, order_id BIGINT NOT NULL, redeemed_at TIMESTAMPTZ NOT NULL,
 code_snapshot VARCHAR(64) NOT NULL, title_snapshot TEXT NOT NULL, type_snapshot TEXT NOT NULL,
 value_snapshot NUMERIC NOT NULL, minimum_subtotal_snapshot NUMERIC NOT NULL,
 maximum_discount_snapshot NUMERIC, calculation_base NUMERIC NOT NULL, applied_discount NUMERIC NOT NULL,
 CONSTRAINT uk_voucher_redemptions_order_id UNIQUE(order_id),
 CONSTRAINT uk_voucher_redemptions_voucher_entitlement_id UNIQUE(voucher_entitlement_id),
 CONSTRAINT fk_voucher_redemptions_owned_order FOREIGN KEY(order_id,customer_id) REFERENCES orders(id,customer_id) ON DELETE RESTRICT,
 CONSTRAINT fk_voucher_redemptions_grant FOREIGN KEY(voucher_entitlement_id,voucher_customer_usage_id,voucher_id,customer_id) REFERENCES voucher_entitlements(id,voucher_customer_usage_id,voucher_id,customer_id) ON DELETE RESTRICT,
 CONSTRAINT ck_voucher_redemptions_snapshot CHECK(code_snapshot ~ '^[A-Z0-9_-]{1,64}$' AND title_snapshot ~ '[^[:space:]]'
  AND value_snapshot::TEXT NOT IN ('NaN','Infinity','-Infinity') AND value_snapshot>0
  AND minimum_subtotal_snapshot::TEXT NOT IN ('NaN','Infinity','-Infinity') AND minimum_subtotal_snapshot>=0 AND TRUNC(minimum_subtotal_snapshot)=minimum_subtotal_snapshot
  AND calculation_base::TEXT NOT IN ('NaN','Infinity','-Infinity') AND calculation_base>0 AND TRUNC(calculation_base)=calculation_base AND calculation_base>=minimum_subtotal_snapshot
  AND applied_discount::TEXT NOT IN ('NaN','Infinity','-Infinity') AND applied_discount>=0 AND TRUNC(applied_discount)=applied_discount AND applied_discount<=calculation_base
  AND (maximum_discount_snapshot IS NULL OR (maximum_discount_snapshot::TEXT NOT IN ('NaN','Infinity','-Infinity') AND maximum_discount_snapshot>=0 AND TRUNC(maximum_discount_snapshot)=maximum_discount_snapshot))
  AND ((type_snapshot='FIXED_AMOUNT' AND TRUNC(value_snapshot)=value_snapshot AND maximum_discount_snapshot IS NULL AND applied_discount=LEAST(value_snapshot,calculation_base))
    OR (type_snapshot='PERCENTAGE' AND value_snapshot<=100 AND TRUNC(value_snapshot,2)=value_snapshot AND applied_discount=FLOOR(LEAST(calculation_base*value_snapshot/100,COALESCE(maximum_discount_snapshot,calculation_base),calculation_base)))))
);
CREATE FUNCTION voucher_order_snapshot(r voucher_redemptions) RETURNS JSONB LANGUAGE SQL IMMUTABLE STRICT AS $$
 SELECT JSONB_BUILD_OBJECT('walletEntitlementId',r.voucher_entitlement_id,'voucherId',r.voucher_id,'code',r.code_snapshot,'title',r.title_snapshot,
 'discountType',r.type_snapshot,'discountValue',r.value_snapshot,'minimumSubtotal',JSONB_BUILD_OBJECT('amount',r.minimum_subtotal_snapshot,'currency','VND'),
 'maximumDiscount',CASE WHEN r.maximum_discount_snapshot IS NULL THEN NULL ELSE JSONB_BUILD_OBJECT('amount',r.maximum_discount_snapshot,'currency','VND') END,
 'calculationBase',JSONB_BUILD_OBJECT('amount',r.calculation_base,'currency','VND'),'appliedDiscount',JSONB_BUILD_OBJECT('amount',r.applied_discount,'currency','VND'),'redeemedAt',TO_CHAR(r.redeemed_at AT TIME ZONE 'UTC','YYYY-MM-DD"T"HH24:MI:SS.US"Z"'));
$$;
CREATE FUNCTION guard_voucher_history() RETURNS TRIGGER LANGUAGE PLPGSQL AS $$
BEGIN
 IF TG_TABLE_NAME='voucher_redemptions' THEN
  RAISE EXCEPTION 'Voucher redemption history is immutable' USING ERRCODE='23514',CONSTRAINT='ct_voucher_redemptions_immutable';
 ELSIF TG_TABLE_NAME='voucher_customer_usages' THEN
  IF ROW(NEW.id,NEW.voucher_id,NEW.customer_id) IS DISTINCT FROM ROW(OLD.id,OLD.voucher_id,OLD.customer_id) THEN
   RAISE EXCEPTION 'Voucher ownership is immutable' USING ERRCODE='23514',CONSTRAINT='ct_voucher_entitlements_immutable';
  END IF;
 ELSIF TG_TABLE_NAME='voucher_entitlements' THEN
  IF TG_OP='INSERT' THEN
   IF NEW.state<>'AVAILABLE' OR NEW.consumed_at IS NOT NULL THEN RAISE EXCEPTION 'Grant must start available' USING ERRCODE='23514',CONSTRAINT='ct_voucher_entitlements_immutable'; END IF;
  ELSIF TG_OP='DELETE' THEN
   RAISE EXCEPTION 'Voucher grant history is retained' USING ERRCODE='23514',CONSTRAINT='ct_voucher_entitlements_immutable';
  ELSIF ROW(NEW.id,NEW.voucher_customer_usage_id,NEW.voucher_id,NEW.customer_id,NEW.granted_at) IS DISTINCT FROM ROW(OLD.id,OLD.voucher_customer_usage_id,OLD.voucher_id,OLD.customer_id,OLD.granted_at)
   OR (OLD.state='CONSUMED' AND ROW(NEW.state,NEW.consumed_at) IS DISTINCT FROM ROW(OLD.state,OLD.consumed_at)) THEN
   RAISE EXCEPTION 'Voucher grant history is immutable' USING ERRCODE='23514',CONSTRAINT='ct_voucher_entitlements_immutable';
  END IF;
 ELSIF TG_TABLE_NAME='orders' THEN
  IF ROW(NEW.voucher_discount,NEW.voucher_snapshot) IS DISTINCT FROM ROW(OLD.voucher_discount,OLD.voucher_snapshot)
   OR (OLD.voucher_snapshot IS NOT NULL AND ROW(NEW.id,NEW.customer_id,NEW.placed_at,NEW.merchandise_total,NEW.payable_total) IS DISTINCT FROM ROW(OLD.id,OLD.customer_id,OLD.placed_at,OLD.merchandise_total,OLD.payable_total)) THEN
   RAISE EXCEPTION 'Original order discount is immutable' USING ERRCODE='23514',CONSTRAINT='ct_orders_voucher_integrity';
  END IF;
 END IF;
 IF TG_OP='DELETE' THEN RETURN OLD; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER ct_voucher_entitlements_immutable BEFORE INSERT OR UPDATE OR DELETE ON voucher_entitlements FOR EACH ROW EXECUTE FUNCTION guard_voucher_history();
CREATE TRIGGER ct_voucher_redemptions_immutable BEFORE UPDATE OR DELETE ON voucher_redemptions FOR EACH ROW EXECUTE FUNCTION guard_voucher_history();
CREATE TRIGGER ct_voucher_usages_immutable BEFORE UPDATE ON voucher_customer_usages FOR EACH ROW EXECUTE FUNCTION guard_voucher_history();
CREATE TRIGGER ct_orders_voucher_snapshot BEFORE UPDATE ON orders FOR EACH ROW EXECUTE FUNCTION guard_voucher_history();
CREATE FUNCTION validate_voucher_final(voucher_key BIGINT) RETURNS VOID LANGUAGE PLPGSQL AS $$
DECLARE definition vouchers%ROWTYPE; u RECORD; g RECORD; redemption_row voucher_redemptions%ROWTYPE; total NUMERIC;
BEGIN
 SELECT * INTO definition FROM vouchers WHERE id=voucher_key FOR UPDATE;
 IF NOT FOUND THEN RETURN; END IF;
 SELECT COUNT(*) INTO total FROM voucher_redemptions WHERE voucher_id=voucher_key;
 IF definition.redeemed_count::NUMERIC<>total THEN RAISE EXCEPTION 'Voucher usage differs from redemptions' USING ERRCODE='23514',CONSTRAINT='ct_voucher_usage_integrity'; END IF;
 FOR u IN SELECT * FROM voucher_customer_usages WHERE voucher_id=voucher_key ORDER BY id FOR UPDATE LOOP
  SELECT COUNT(*) INTO total FROM voucher_redemptions WHERE voucher_customer_usage_id=u.id;
  IF total<>u.redeemed_count::NUMERIC OR (definition.per_customer_usage_limit IS NOT NULL AND total>definition.per_customer_usage_limit) THEN
   RAISE EXCEPTION 'Customer usage differs from redemptions' USING ERRCODE='23514',CONSTRAINT='ct_voucher_usage_integrity';
  END IF;
 END LOOP;
 FOR g IN SELECT * FROM voucher_entitlements WHERE voucher_id=voucher_key ORDER BY id FOR UPDATE LOOP
  SELECT * INTO redemption_row FROM voucher_redemptions WHERE voucher_entitlement_id=g.id;
  IF (g.state='CONSUMED') IS DISTINCT FROM FOUND OR (g.state='CONSUMED' AND (g.consumed_at IS DISTINCT FROM redemption_row.redeemed_at OR EXISTS(SELECT 1 FROM carts WHERE voucher_entitlement_id=g.id))) THEN
   RAISE EXCEPTION 'Grant does not match its original redemption' USING ERRCODE='23514',CONSTRAINT='ct_voucher_usage_integrity';
  END IF;
 END LOOP;
 IF EXISTS(SELECT 1 FROM voucher_redemptions r JOIN orders o ON o.id=r.order_id WHERE r.voucher_id=voucher_key AND
   (o.customer_id<>r.customer_id OR o.placed_at<>r.redeemed_at OR o.merchandise_total<>r.calculation_base OR o.voucher_discount<>r.applied_discount OR o.voucher_snapshot IS DISTINCT FROM voucher_order_snapshot(r))) THEN
  RAISE EXCEPTION 'Order discount differs from its redemption' USING ERRCODE='23514',CONSTRAINT='ct_orders_voucher_integrity';
 END IF;
END $$;
CREATE FUNCTION check_voucher_final() RETURNS TRIGGER LANGUAGE PLPGSQL AS $$
DECLARE voucher_key BIGINT; target_order BIGINT;
BEGIN
 IF TG_TABLE_NAME='vouchers' THEN voucher_key:=COALESCE(NEW.id,OLD.id);
 ELSIF TG_TABLE_NAME='orders' THEN
  target_order:=COALESCE(NEW.id,OLD.id);
  IF EXISTS(SELECT 1 FROM orders o WHERE o.id=target_order AND o.voucher_snapshot IS NOT NULL AND NOT EXISTS(SELECT 1 FROM voucher_redemptions r WHERE r.order_id=o.id)) THEN
   RAISE EXCEPTION 'Order discount requires redemption' USING ERRCODE='23514',CONSTRAINT='ct_orders_voucher_integrity';
  END IF;
  SELECT voucher_id INTO voucher_key FROM voucher_redemptions WHERE order_id=target_order;
 ELSIF TG_TABLE_NAME='carts' THEN
  -- Cart's FK takes a grant key-share lock. Never reverse from that lock into
  -- quota locks: purchase reconciliation already locks grants before checking
  -- retained Cart references. Selection itself only checks the retained state.
  IF NEW.voucher_entitlement_id IS NOT NULL AND EXISTS(
    SELECT 1 FROM voucher_entitlements WHERE id=NEW.voucher_entitlement_id AND state='CONSUMED') THEN
   RAISE EXCEPTION 'Consumed grant cannot remain selected' USING ERRCODE='23514',CONSTRAINT='ct_voucher_usage_integrity';
  END IF;
  RETURN NULL;
 ELSE voucher_key:=COALESCE(NEW.voucher_id,OLD.voucher_id);
 END IF;
 IF voucher_key IS NOT NULL THEN PERFORM validate_voucher_final(voucher_key); END IF;
 RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER ct_vouchers_usage AFTER INSERT OR UPDATE OR DELETE ON vouchers DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_voucher_final();
CREATE CONSTRAINT TRIGGER ct_voucher_usages_count AFTER INSERT OR UPDATE OR DELETE ON voucher_customer_usages DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_voucher_final();
CREATE CONSTRAINT TRIGGER ct_voucher_grants_count AFTER INSERT OR UPDATE OR DELETE ON voucher_entitlements DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_voucher_final();
CREATE CONSTRAINT TRIGGER ct_voucher_redemptions_count AFTER INSERT OR UPDATE OR DELETE ON voucher_redemptions DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_voucher_final();
CREATE CONSTRAINT TRIGGER ct_orders_voucher_integrity AFTER INSERT OR DELETE ON orders DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_voucher_final();
CREATE CONSTRAINT TRIGGER ct_carts_voucher_integrity AFTER INSERT OR UPDATE OR DELETE ON carts DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_voucher_final();

-- Preserve checkout_receipt_is_valid(JSONB) as the original V25/v1 validator.
CREATE FUNCTION checkout_receipt_v2_is_valid(body JSONB) RETURNS BOOLEAN LANGUAGE PLPGSQL IMMUTABLE AS $$
DECLARE header JSONB; legacy JSONB; snapshot JSONB; discount NUMERIC; base NUMERIC; payable NUMERIC;
BEGIN
 header:=body->'order';
 IF JSONB_TYPEOF(header) IS DISTINCT FROM 'object' OR NOT header ? 'voucher' OR NOT header ? 'voucherDiscount'
    OR NOT checkout_money_is_valid(header->'voucherDiscount') THEN RETURN FALSE; END IF;
 discount:=(header->'voucherDiscount'->>'amount')::NUMERIC;
 base:=(header->'merchandiseTotal'->>'amount')::NUMERIC;
 payable:=(header->'payableTotal'->>'amount')::NUMERIC;
 IF base IS NULL OR payable IS NULL OR NOT checkout_money_is_valid(header->'payableTotal') OR discount>base OR payable<>base-discount THEN RETURN FALSE; END IF;
 snapshot:=header->'voucher';
 IF snapshot='null'::JSONB THEN
  IF discount<>0 THEN RETURN FALSE; END IF;
 ELSE
  IF JSONB_TYPEOF(snapshot) IS DISTINCT FROM 'object'
   OR snapshot-ARRAY['walletEntitlementId','voucherId','code','title','discountType','discountValue','minimumSubtotal','maximumDiscount','calculationBase','appliedDiscount','redeemedAt']<>'{}'::JSONB
   OR NOT snapshot ?& ARRAY['walletEntitlementId','voucherId','code','title','discountType','discountValue','minimumSubtotal','maximumDiscount','calculationBase','appliedDiscount','redeemedAt']
   OR (snapshot->>'walletEntitlementId')!~'^[1-9][0-9]*$' OR (snapshot->>'walletEntitlementId')::BIGINT<=0
   OR (snapshot->>'voucherId')!~'^[1-9][0-9]*$' OR (snapshot->>'voucherId')::BIGINT<=0
   OR NOT checkout_money_is_valid(snapshot->'calculationBase') OR snapshot->'calculationBase' IS DISTINCT FROM header->'merchandiseTotal'
   OR snapshot->'appliedDiscount' IS DISTINCT FROM header->'voucherDiscount'
   OR (snapshot->>'redeemedAt')::TIMESTAMPTZ IS DISTINCT FROM (header->>'placedAt')::TIMESTAMPTZ THEN RETURN FALSE; END IF;
 END IF;
 legacy:=JSONB_SET(body,'{order}',(header-ARRAY['voucherDiscount','voucher'])||JSONB_BUILD_OBJECT('payableTotal',header->'merchandiseTotal'));
 RETURN checkout_receipt_is_valid(legacy);
EXCEPTION WHEN OTHERS THEN RETURN FALSE;
END $$;
