CREATE OR REPLACE FUNCTION check_checkout_receipt_integrity() RETURNS TRIGGER LANGUAGE PLPGSQL AS $$
DECLARE original JSONB; discount NUMERIC; snapshot JSONB;
BEGIN
 SELECT JSONB_BUILD_OBJECT('id',o.id,'orderNumber',o.order_number,'status',o.status,
 'recipientNameSnapshot',o.recipient_name_snapshot,'recipientPhoneSnapshot',o.recipient_phone_snapshot,'deliveryAddressSnapshot',o.delivery_address_snapshot,
 'merchandiseTotal',JSONB_BUILD_OBJECT('amount',o.merchandise_total,'currency','VND'),'payableTotal',JSONB_BUILD_OBJECT('amount',o.payable_total,'currency','VND'),
 'items',(SELECT JSONB_AGG(JSONB_BUILD_OBJECT('id',i.id,'productNameSnapshot',i.product_name_snapshot,'variantSkuSnapshot',i.variant_sku_snapshot,
 'variantOptionsSnapshot',i.variant_options_snapshot,'quantity',i.quantity,'unitPriceSnapshot',JSONB_BUILD_OBJECT('amount',i.unit_price_snapshot,'currency','VND'),
 'lineTotal',JSONB_BUILD_OBJECT('amount',i.line_total,'currency','VND')) ORDER BY i.id) FROM order_items i WHERE i.order_id=o.id)),o.voucher_discount,o.voucher_snapshot
 INTO original,discount,snapshot FROM orders o WHERE o.id=NEW.order_id AND o.customer_id=NEW.customer_id AND o.placed_at=NEW.created_at;
 IF NEW.receipt_version=2 THEN original:=original||JSONB_BUILD_OBJECT('voucherDiscount',JSONB_BUILD_OBJECT('amount',discount,'currency','VND'),'voucher',snapshot); END IF;
 IF original IS NULL OR original<>(NEW.receipt_body->'order')-'placedAt' THEN
  RAISE EXCEPTION 'Checkout receipt does not match original order' USING ERRCODE='23514',CONSTRAINT='ct_checkout_receipts_integrity';
 END IF;
 RETURN NULL;
END $$;
