CREATE TABLE inventory_balances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    original_variant_id UUID NOT NULL,
    product_variant_id UUID,
    stock BIGINT NOT NULL DEFAULT 0,
    reserved BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uk_inventory_balances_original_variant_id UNIQUE (original_variant_id),
    CONSTRAINT uk_inventory_balances_product_variant_id UNIQUE (product_variant_id),
    CONSTRAINT uk_inventory_balances_id_original_variant_id UNIQUE (id,original_variant_id),
    CONSTRAINT fk_inventory_balances_product_variant_id FOREIGN KEY (product_variant_id) REFERENCES product_variants(id) ON DELETE SET NULL,
    CONSTRAINT ck_inventory_balances_quantities CHECK (stock>=0 AND reserved>=0 AND reserved<=stock),
    CONSTRAINT ck_inventory_balances_variant_identity CHECK (product_variant_id IS NULL OR product_variant_id=original_variant_id)
);
INSERT INTO inventory_balances(original_variant_id,product_variant_id) SELECT id,id FROM product_variants;

CREATE FUNCTION initialize_variant_inventory() RETURNS TRIGGER LANGUAGE PLPGSQL AS $$
BEGIN
    INSERT INTO inventory_balances(original_variant_id,product_variant_id) VALUES (NEW.id,NEW.id);
    RETURN NEW;
END $$;
CREATE TRIGGER ct_product_variants_inventory_initialize AFTER INSERT ON product_variants
FOR EACH ROW EXECUTE FUNCTION initialize_variant_inventory();

CREATE TABLE inventory_reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    order_item_id BIGINT NOT NULL,
    inventory_balance_id BIGINT NOT NULL,
    original_variant_id UUID NOT NULL,
    quantity INTEGER NOT NULL,
    state TEXT NOT NULL DEFAULT 'ACTIVE',
    reserved_at TIMESTAMPTZ NOT NULL,
    resolved_at TIMESTAMPTZ,
    CONSTRAINT fk_inventory_reservations_order_id FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_reservations_order_item_id_order_id FOREIGN KEY (order_item_id,order_id) REFERENCES order_items(id,order_id) ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_reservations_balance_variant FOREIGN KEY (inventory_balance_id,original_variant_id) REFERENCES inventory_balances(id,original_variant_id) ON DELETE RESTRICT,
    CONSTRAINT uk_inventory_reservations_order_item_id UNIQUE (order_item_id),
    CONSTRAINT uk_inventory_reservations_order_id_original_variant_id UNIQUE (order_id,original_variant_id),
    CONSTRAINT ck_inventory_reservations_quantity CHECK (quantity BETWEEN 1 AND 999),
    CONSTRAINT ck_inventory_reservations_state CHECK (state IN ('ACTIVE','CONSUMED','RELEASED')),
    CONSTRAINT ck_inventory_reservations_times CHECK ((state='ACTIVE')=(resolved_at IS NULL) AND (resolved_at IS NULL OR resolved_at>=reserved_at))
);
CREATE INDEX idx_inventory_reservations_inventory_balance_id_state ON inventory_reservations(inventory_balance_id,state);

CREATE FUNCTION guard_inventory_reservation() RETURNS TRIGGER LANGUAGE PLPGSQL AS $$
BEGIN
    IF TG_OP='INSERT' THEN
        IF NEW.state<>'ACTIVE' OR NEW.resolved_at IS NOT NULL OR
           NOT EXISTS (SELECT 1 FROM orders WHERE id=NEW.order_id AND inventory_managed) OR
           NOT EXISTS (SELECT 1 FROM inventory_balances WHERE id=NEW.inventory_balance_id AND product_variant_id=NEW.original_variant_id) THEN
            RAISE EXCEPTION 'Invalid inventory allocation insertion' USING ERRCODE='23514',CONSTRAINT='ct_inventory_reservations_immutable';
        END IF;
        RETURN NEW;
    END IF;
    IF TG_OP='DELETE' THEN
        RAISE EXCEPTION 'Inventory allocation history is retained' USING ERRCODE='23514',CONSTRAINT='ct_inventory_reservations_immutable';
    END IF;
    IF ROW(NEW.id,NEW.order_id,NEW.order_item_id,NEW.inventory_balance_id,NEW.original_variant_id,NEW.quantity,NEW.reserved_at)
       IS DISTINCT FROM ROW(OLD.id,OLD.order_id,OLD.order_item_id,OLD.inventory_balance_id,OLD.original_variant_id,OLD.quantity,OLD.reserved_at)
       OR (OLD.state<>'ACTIVE' AND ROW(NEW.state,NEW.resolved_at) IS DISTINCT FROM ROW(OLD.state,OLD.resolved_at)) THEN
        RAISE EXCEPTION 'Inventory allocation identity or terminal history is immutable' USING ERRCODE='23514',CONSTRAINT='ct_inventory_reservations_immutable';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER ct_inventory_reservations_immutable BEFORE INSERT OR UPDATE OR DELETE ON inventory_reservations
FOR EACH ROW EXECUTE FUNCTION guard_inventory_reservation();

CREATE FUNCTION guard_inventory_balance() RETURNS TRIGGER LANGUAGE PLPGSQL AS $$
BEGIN
    IF TG_OP='DELETE' THEN
        IF OLD.stock<>0 OR OLD.reserved<>0 OR EXISTS (SELECT 1 FROM inventory_reservations WHERE inventory_balance_id=OLD.id) THEN
            RAISE EXCEPTION 'Inventory balance with stock or history is retained' USING ERRCODE='23514',CONSTRAINT='ct_inventory_balance_retention';
        END IF;
        RETURN OLD;
    END IF;
    IF NEW.id<>OLD.id OR NEW.original_variant_id<>OLD.original_variant_id OR
       (OLD.product_variant_id IS NULL AND NEW.product_variant_id IS NOT NULL) OR
       (NEW.product_variant_id IS DISTINCT FROM OLD.product_variant_id AND EXISTS
        (SELECT 1 FROM inventory_reservations WHERE inventory_balance_id=OLD.id AND state='ACTIVE')) THEN
        RAISE EXCEPTION 'Inventory balance identity or active catalog reference cannot change' USING ERRCODE='23514',CONSTRAINT='ct_inventory_balance_retention';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER ct_inventory_balance_retention BEFORE UPDATE OR DELETE ON inventory_balances
FOR EACH ROW EXECUTE FUNCTION guard_inventory_balance();

CREATE FUNCTION guard_order_inventory_participation() RETURNS TRIGGER LANGUAGE PLPGSQL AS $$
BEGIN
    IF NEW.inventory_managed IS DISTINCT FROM OLD.inventory_managed THEN
        RAISE EXCEPTION 'Order inventory participation is immutable' USING ERRCODE='23514',CONSTRAINT='ct_orders_inventory_participation';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER ct_orders_inventory_participation BEFORE UPDATE ON orders
FOR EACH ROW EXECUTE FUNCTION guard_order_inventory_participation();

CREATE FUNCTION validate_inventory_order(affected_id BIGINT) RETURNS VOID LANGUAGE PLPGSQL AS $$
DECLARE parent orders%ROWTYPE; expected_state TEXT; expected_time TIMESTAMPTZ;
BEGIN
    SELECT * INTO parent FROM orders WHERE id=affected_id;
    IF NOT FOUND THEN RETURN; END IF;
    IF NOT parent.inventory_managed THEN
        IF EXISTS (SELECT 1 FROM inventory_reservations WHERE order_id=affected_id) THEN
            RAISE EXCEPTION 'Legacy order cannot own inventory allocations' USING ERRCODE='23514',CONSTRAINT='ct_orders_inventory_integrity';
        END IF;
        RETURN;
    END IF;
    expected_state := CASE parent.status WHEN 'CANCELLED' THEN 'RELEASED' WHEN 'COMPLETED' THEN 'CONSUMED' ELSE 'ACTIVE' END;
    expected_time := CASE parent.status WHEN 'CANCELLED' THEN parent.cancelled_at WHEN 'COMPLETED' THEN parent.completed_at ELSE NULL END;
    IF NOT EXISTS (SELECT 1 FROM order_items WHERE order_id=affected_id)
       OR EXISTS (
        SELECT 1 FROM order_items i LEFT JOIN inventory_reservations r ON r.order_item_id=i.id
        LEFT JOIN inventory_balances b ON b.id=r.inventory_balance_id
        WHERE i.order_id=affected_id AND (r.id IS NULL OR r.order_id<>affected_id OR r.quantity<>i.quantity
            OR r.state<>expected_state OR r.reserved_at<>parent.placed_at OR r.resolved_at IS DISTINCT FROM expected_time
            OR (i.product_variant_id IS NOT NULL AND i.product_variant_id<>r.original_variant_id)
            OR (r.state='ACTIVE' AND (i.product_variant_id IS NULL OR b.product_variant_id IS DISTINCT FROM r.original_variant_id))))
       OR EXISTS (SELECT 1 FROM inventory_reservations r LEFT JOIN order_items i ON i.id=r.order_item_id AND i.order_id=r.order_id
                  WHERE r.order_id=affected_id AND i.id IS NULL) THEN
        RAISE EXCEPTION 'Managed order requires its exact attributed allocation set' USING ERRCODE='23514',CONSTRAINT='ct_orders_inventory_integrity';
    END IF;
END $$;

CREATE FUNCTION check_inventory_order_integrity() RETURNS TRIGGER LANGUAGE PLPGSQL AS $$
DECLARE affected BIGINT[]; current_id BIGINT;
BEGIN
    IF TG_TABLE_NAME='orders' THEN
        IF TG_OP='DELETE' THEN affected:=ARRAY[OLD.id]; ELSE affected:=ARRAY[NEW.id]; END IF;
    ELSIF TG_OP='INSERT' THEN affected:=ARRAY[NEW.order_id];
    ELSIF TG_OP='DELETE' THEN affected:=ARRAY[OLD.order_id];
    ELSE affected:=ARRAY[OLD.order_id,NEW.order_id]; END IF;
    FOR current_id IN SELECT DISTINCT id FROM unnest(affected) id ORDER BY id LOOP
        -- Owning services hold existing order locks before balances; no reverse order lock here.
        PERFORM validate_inventory_order(current_id);
    END LOOP;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER ct_orders_inventory_integrity AFTER INSERT OR UPDATE OR DELETE ON orders
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_inventory_order_integrity();
CREATE CONSTRAINT TRIGGER ct_order_items_inventory_integrity AFTER INSERT OR UPDATE OR DELETE ON order_items
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_inventory_order_integrity();
CREATE CONSTRAINT TRIGGER ct_inventory_reservations_order_integrity AFTER INSERT OR UPDATE OR DELETE ON inventory_reservations
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_inventory_order_integrity();

CREATE FUNCTION check_inventory_balance_integrity() RETURNS TRIGGER LANGUAGE PLPGSQL AS $$
DECLARE affected BIGINT[]; row_balance RECORD; actual NUMERIC;
BEGIN
    IF TG_TABLE_NAME='inventory_balances' THEN
        IF TG_OP='DELETE' THEN affected:=ARRAY[OLD.id]; ELSE affected:=ARRAY[NEW.id]; END IF;
    ELSIF TG_OP='INSERT' THEN affected:=ARRAY[NEW.inventory_balance_id];
    ELSIF TG_OP='DELETE' THEN affected:=ARRAY[OLD.inventory_balance_id];
    ELSE affected:=ARRAY[OLD.inventory_balance_id,NEW.inventory_balance_id]; END IF;
    FOR row_balance IN SELECT id,original_variant_id FROM inventory_balances WHERE id=ANY(affected) ORDER BY original_variant_id FOR UPDATE LOOP
        SELECT COALESCE(SUM(quantity::NUMERIC),0) INTO actual FROM inventory_reservations WHERE inventory_balance_id=row_balance.id AND state='ACTIVE';
        IF NOT EXISTS (SELECT 1 FROM inventory_balances WHERE id=row_balance.id AND reserved::NUMERIC=actual) THEN
            RAISE EXCEPTION 'Inventory counter differs from active allocations' USING ERRCODE='23514',CONSTRAINT='ct_inventory_balances_allocation_integrity';
        END IF;
    END LOOP;
    RETURN NULL;
END $$;
CREATE CONSTRAINT TRIGGER ct_inventory_balances_allocation_integrity AFTER INSERT OR UPDATE OR DELETE ON inventory_balances
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_inventory_balance_integrity();
CREATE CONSTRAINT TRIGGER ct_inventory_reservations_allocation_integrity AFTER INSERT OR UPDATE OR DELETE ON inventory_reservations
DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_inventory_balance_integrity();

CREATE OR REPLACE FUNCTION checkout_receipt_is_valid(body JSONB) RETURNS BOOLEAN
LANGUAGE PLPGSQL IMMUTABLE AS $$
DECLARE
    header JSONB;
    item JSONB;
    skipped JSONB;
    previous_id BIGINT := 0;
    current_id BIGINT;
    quantity_value NUMERIC;
    total NUMERIC := 0;
BEGIN
    IF JSONB_TYPEOF(body) IS DISTINCT FROM 'object'
        OR body - ARRAY['order','skippedItems'] <> '{}'::JSONB
        OR JSONB_TYPEOF(body->'order') IS DISTINCT FROM 'object'
        OR JSONB_TYPEOF(body->'skippedItems') IS DISTINCT FROM 'array' THEN RETURN FALSE; END IF;
    header := body->'order';
    IF header - ARRAY['id','orderNumber','placedAt','status','recipientNameSnapshot','recipientPhoneSnapshot','deliveryAddressSnapshot','items','merchandiseTotal','payableTotal'] <> '{}'::JSONB
        OR JSONB_TYPEOF(header->'id') IS DISTINCT FROM 'number'
        OR (header->>'id') !~ '^[1-9][0-9]*$' OR (header->>'id')::BIGINT <= 0
        OR header->>'status' IS DISTINCT FROM 'PENDING'
        OR JSONB_TYPEOF(header->'items') IS DISTINCT FROM 'array'
        OR JSONB_ARRAY_LENGTH(header->'items') = 0
        OR NOT checkout_money_is_valid(header->'merchandiseTotal')
        OR NOT checkout_money_is_valid(header->'payableTotal') THEN RETURN FALSE; END IF;
    FOREACH item IN ARRAY ARRAY[header->'orderNumber',header->'placedAt',header->'recipientNameSnapshot',header->'recipientPhoneSnapshot',header->'deliveryAddressSnapshot'] LOOP
        IF JSONB_TYPEOF(item) IS DISTINCT FROM 'string' OR (item #>> '{}') !~ '[^[:space:]]' THEN RETURN FALSE; END IF;
    END LOOP;
    PERFORM (header->>'placedAt')::TIMESTAMPTZ;
    FOR item IN SELECT value FROM JSONB_ARRAY_ELEMENTS(header->'items') LOOP
        IF JSONB_TYPEOF(item) IS DISTINCT FROM 'object'
            OR item - ARRAY['id','productNameSnapshot','variantSkuSnapshot','variantOptionsSnapshot','quantity','unitPriceSnapshot','lineTotal'] <> '{}'::JSONB
            OR JSONB_TYPEOF(item->'id') IS DISTINCT FROM 'number'
            OR (item->>'id') !~ '^[1-9][0-9]*$'
            OR JSONB_TYPEOF(item->'productNameSnapshot') IS DISTINCT FROM 'string'
            OR (item->>'productNameSnapshot') !~ '[^[:space:]]'
            OR JSONB_TYPEOF(item->'variantSkuSnapshot') IS DISTINCT FROM 'string'
            OR (item->>'variantSkuSnapshot') !~ '[^[:space:]]'
            OR NOT COALESCE(order_options_are_strings(item->'variantOptionsSnapshot'), FALSE)
            OR JSONB_TYPEOF(item->'quantity') IS DISTINCT FROM 'number'
            OR NOT checkout_money_is_valid(item->'unitPriceSnapshot')
            OR NOT checkout_money_is_valid(item->'lineTotal') THEN RETURN FALSE; END IF;
        current_id := (item->>'id')::BIGINT;
        IF current_id <= previous_id THEN RETURN FALSE; END IF;
        previous_id := current_id;
        quantity_value := (item->>'quantity')::NUMERIC;
        IF quantity_value NOT BETWEEN 1 AND 999 OR TRUNC(quantity_value) <> quantity_value
            OR (item->'lineTotal'->>'amount')::NUMERIC <> quantity_value * (item->'unitPriceSnapshot'->>'amount')::NUMERIC THEN RETURN FALSE; END IF;
        total := total + (item->'lineTotal'->>'amount')::NUMERIC;
    END LOOP;
    IF total <> (header->'merchandiseTotal'->>'amount')::NUMERIC
        OR total <> (header->'payableTotal'->>'amount')::NUMERIC THEN RETURN FALSE; END IF;
    previous_id := 0;
    FOR skipped IN SELECT value FROM JSONB_ARRAY_ELEMENTS(body->'skippedItems') LOOP
        IF JSONB_TYPEOF(skipped) IS DISTINCT FROM 'object'
            OR skipped - ARRAY['cartItemId','reason'] <> '{}'::JSONB
            OR JSONB_TYPEOF(skipped->'cartItemId') IS DISTINCT FROM 'number'
            OR (skipped->>'cartItemId') !~ '^[1-9][0-9]*$'
            OR JSONB_TYPEOF(skipped->'reason') IS DISTINCT FROM 'string'
            OR skipped->>'reason' NOT IN ('VARIANT_UNAVAILABLE','PRODUCT_UNAVAILABLE','PRODUCT_NOT_FOR_SALE','INVALID_QUANTITY','INVALID_PRICE','INVENTORY_UNAVAILABLE','INSUFFICIENT_STOCK') THEN RETURN FALSE; END IF;
        current_id := (skipped->>'cartItemId')::BIGINT;
        IF current_id <= previous_id THEN RETURN FALSE; END IF;
        previous_id := current_id;
    END LOOP;
    RETURN TRUE;
EXCEPTION WHEN OTHERS THEN RETURN FALSE;
END;
$$;

